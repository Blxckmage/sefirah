CARD_ASPECT = 0.58
MARGIN = 72
TEXT_COLUMN = 345
GAP = 46
LEFT_OFFSET = -144


def lock_layout(size: tuple[int, int], panel_x: int, scale: int) -> dict[str, int]:
    w, h = size
    tall = int((h - 2 * MARGIN) * CARD_ASPECT)
    card_w = max(0, min(320, tall))
    card_w -= card_w % scale
    lock_x = w - MARGIN - card_w - GAP - TEXT_COLUMN
    lock_x = max(lock_x, panel_x + MARGIN)
    return {"lock_x": lock_x, "card_w": card_w}


def parse_outputs(outputs: dict) -> tuple[int, int] | None:
    # Hyprlock's viewport is the buffer size: logical pixels times scale, already
    # rotated. Raw modes ignore both, so a portrait or fractional display breaks.
    sizes = []
    for output in outputs.values():
        logical = output.get("logical")
        if not logical:
            continue
        scale = logical.get("scale", 1)
        sizes.append((round(logical["width"] * scale), round(logical["height"] * scale)))
    return max(sizes, key=lambda s: s[0] * s[1]) if sizes else None


def screen_size() -> tuple[int, int]:
    niri = shutil.which("niri")
    if niri:
        try:
            out = subprocess.run(
                [niri, "msg", "-j", "outputs"],
                capture_output=True,
                text=True,
                check=True,
            ).stdout
            size = parse_outputs(json.loads(out))
            if size:
                return size
        except (OSError, subprocess.SubprocessError, KeyError, TypeError, ValueError):
            pass
    return (1920, 1080)


